import React, { useState } from 'react';
import type { ReportAnalysisResult, VerificationStatus, UrgencyLevel } from '../types';

interface ResultsPanelProps {
  result: ReportAnalysisResult | null;
  isLoading: boolean;
}

export const ResultsPanel: React.FC<ResultsPanelProps> = ({ result, isLoading }) => {
  const [showRawJson, setShowRawJson] = useState(false);

  if (isLoading) {
    return (
      <section className="card" aria-busy="true" aria-live="polite">
        <div className="loading-indicator">
          <div className="spinner-outer" />
          <div style={{ textAlign: 'center' }}>
            <h3 className="loading-title">Synthesizing Incident Intelligence</h3>
            <p className="loading-subtitle">
              Evaluating facts, cross-referencing locations, and assessing verification status...
            </p>
          </div>
        </div>
      </section>
    );
  }

  if (!result) {
    return (
      <section className="card" aria-label="Structured Analysis Results">
        <div className="results-empty-state">
          <div className="empty-state-icon" aria-hidden="true">
            <svg
              width="32"
              height="32"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <circle cx="12" cy="12" r="10" />
              <line x1="12" y1="16" x2="12" y2="12" />
              <line x1="12" y1="8" x2="12.01" y2="8" />
            </svg>
          </div>
          <h3 className="empty-state-title">Awaiting Incident Report</h3>
          <p className="empty-state-desc">
            Select a sample test scenario on the left or paste an unstructured report to generate
            trustworthy, structured intelligence and actionable guidance.
          </p>
        </div>
      </section>
    );
  }

  // Helper styling for verification status
  const getStatusClass = (status: VerificationStatus): string => {
    switch (status) {
      case 'Verified':
        return 'verified';
      case 'Needs More Information':
        return 'needsinfo';
      case 'Unverified':
      default:
        return 'unverified';
    }
  };

  const getUrgencyClass = (urgency: UrgencyLevel): string => {
    switch (urgency) {
      case 'Critical':
        return 'critical';
      case 'High':
        return 'high';
      case 'Medium':
        return 'medium';
      case 'Low':
      default:
        return 'low';
    }
  };

  return (
    <section className="card" id="results-panel" aria-label="Structured Intelligence Results">
      <div className="results-container">
        {/* Explicit Engine Label Notice */}
        {result.metadata.isDemoFallback ? (
          <aside
            id="demo-fallback-notice"
            className="demo-fallback-banner"
            role="note"
            aria-label="Development Demo Notice"
          >
            <span className="demo-badge">DEVELOPMENT DEMO</span>
            <span className="demo-notice-text">
              <strong>Demo Mode:</strong> No <code>GEMINI_API_KEY</code> detected on the server. This result was generated by the <strong>local rule-based heuristic demo parser</strong> for offline development &mdash; <em>it did NOT come from Google Gemini</em>. Set <code>GEMINI_API_KEY</code> in server <code>.env</code> to activate live Gemini AI.
            </span>
          </aside>
        ) : (
          <aside
            id="gemini-live-notice"
            className="gemini-live-banner"
            role="note"
            aria-label="Live Gemini Analysis Notice"
          >
            <span className="live-badge">GEMINI AI ACTIVE</span>
            <span className="live-notice-text">
              {result.metadata.engineNotice || `Analyzed using Google Gemini (${result.metadata.modelUsed}) via official @google/genai SDK.`}
            </span>
          </aside>
        )}

        {/* Header Bar with Badges */}
        <div className="result-header-bar">
          <div className="header-badges">
            {/* Status Label (Unverified | Needs More Information | Verified) */}
            <span
              id="verification-status-badge"
              className={`status-badge ${getStatusClass(result.verificationStatus)}`}
            >
              {result.verificationStatus === 'Verified' && (
                <svg
                  width="14"
                  height="14"
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="3"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  aria-hidden="true"
                >
                  <polyline points="20 6 9 17 4 12" />
                </svg>
              )}
              {result.verificationStatus === 'Unverified' && (
                <svg
                  width="14"
                  height="14"
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2.5"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  aria-hidden="true"
                >
                  <circle cx="12" cy="12" r="10" />
                  <line x1="12" y1="8" x2="12" y2="12" />
                  <line x1="12" y1="16" x2="12.01" y2="16" />
                </svg>
              )}
              {result.verificationStatus === 'Needs More Information' && (
                <svg
                  width="14"
                  height="14"
                  viewBox="0 0 24 24"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="2.5"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  aria-hidden="true"
                >
                  <circle cx="12" cy="12" r="10" />
                  <path d="M9.09 9a3 3 0 0 1 5.83 1c0 2-3 3-3 3" />
                  <line x1="12" y1="17" x2="12.01" y2="17" />
                </svg>
              )}
              {result.verificationStatus}
            </span>

            {/* Urgency Badge */}
            <span
              id="urgency-badge"
              className={`urgency-badge ${getUrgencyClass(result.urgency)}`}
            >
              Urgency: {result.urgency}
            </span>

            {/* Category */}
            <span id="result-category-badge" className="category-tag">
              {result.category}
            </span>
          </div>

          <button
            type="button"
            id="toggle-raw-json-btn"
            className="btn-ghost"
            style={{ padding: '6px 12px', fontSize: '0.78rem' }}
            onClick={() => setShowRawJson(!showRawJson)}
          >
            {showRawJson ? 'Hide Raw JSON' : 'Inspect JSON'}
          </button>
        </div>

        {/* Headline & Overview */}
        <div className="summary-block" id="summary-section">
          <h3 className="summary-headline" id="summary-headline">
            {result.summary.headline}
          </h3>
          <p className="summary-overview" id="summary-overview">
            {result.summary.overview}
          </p>
        </div>

        {/* Verification Status Rationale Callout */}
        <div
          className={`verification-callout ${getStatusClass(result.verificationStatus)}`}
          id="verification-reasoning-callout"
        >
          <div className="callout-icon" aria-hidden="true">
            <svg
              width="18"
              height="18"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z" />
            </svg>
          </div>
          <div>
            <div style={{ fontWeight: 600, marginBottom: '2px' }}>
              Verification Rationale ({result.verificationStatus})
            </div>
            <div>{result.verificationReasoning}</div>
          </div>
        </div>

        {/* Location & Time Grid */}
        <div className="metrics-grid">
          {/* Location */}
          <div className="metric-card" id="location-metric-card">
            <div className="metric-title">
              <svg
                width="14"
                height="14"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden="true"
              >
                <path d="M20 10c0 6-8 12-8 12s-8-6-8-12a8 8 0 0 1 16 0Z" />
                <circle cx="12" cy="10" r="3" />
              </svg>
              Location Extracted
            </div>
            <div className="metric-val" id="extracted-location-val">
              {result.location.extracted}
            </div>
            <div className="metric-sub">
              {result.location.landmarkOrCrossStreet
                ? `Landmark/Cross-street: ${result.location.landmarkOrCrossStreet}`
                : `Confidence: ${result.location.confidence}`}
            </div>
          </div>

          {/* Time */}
          <div className="metric-card" id="time-metric-card">
            <div className="metric-title">
              <svg
                width="14"
                height="14"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden="true"
              >
                <circle cx="12" cy="12" r="10" />
                <polyline points="12 6 12 12 16 14" />
              </svg>
              Time / Timing
            </div>
            <div className="metric-val" id="extracted-time-val">
              {result.time.extracted}
            </div>
            <div className="metric-sub">
              {result.time.timeframe
                ? `Timeframe: ${result.time.timeframe}`
                : `Confidence: ${result.time.confidence}`}
            </div>
          </div>
        </div>

        {/* Facts & Missing Info Split */}
        <div className="details-split">
          {/* Key Facts */}
          <div className="details-column" id="key-facts-card">
            <div className="column-header facts">
              <svg
                width="16"
                height="16"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2.5"
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden="true"
              >
                <polyline points="20 6 9 17 4 12" />
              </svg>
              <span>Key Extracted Facts ({result.keyFacts.length})</span>
            </div>
            <ul className="details-list" id="key-facts-list">
              {result.keyFacts.length > 0 ? (
                result.keyFacts.map((fact, idx) => (
                  <li key={idx} className="details-item">
                    <span className="details-bullet" style={{ color: '#38bdf8' }}>
                      &bull;
                    </span>
                    <span>{fact}</span>
                  </li>
                ))
              ) : (
                <li className="details-item" style={{ color: 'var(--text-muted)' }}>
                  No unambiguous factual assertions identified.
                </li>
              )}
            </ul>
          </div>

          {/* Missing Information */}
          <div className="details-column" id="missing-info-card">
            <div className="column-header missing">
              <svg
                width="16"
                height="16"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden="true"
              >
                <circle cx="12" cy="12" r="10" />
                <line x1="12" y1="8" x2="12" y2="12" />
                <line x1="12" y1="16" x2="12.01" y2="16" />
              </svg>
              <span>Missing Information ({result.missingInformation.length})</span>
            </div>
            <ul className="details-list" id="missing-info-list">
              {result.missingInformation.length > 0 ? (
                result.missingInformation.map((item, idx) => (
                  <li key={idx} className="details-item">
                    <span className="details-bullet" style={{ color: '#f97316' }}>
                      &bull;
                    </span>
                    <span>{item}</span>
                  </li>
                ))
              ) : (
                <li className="details-item" style={{ color: 'var(--text-muted)' }}>
                  All baseline parameters accounted for.
                </li>
              )}
            </ul>
          </div>
        </div>

        {/* Suggested Next Steps */}
        <div className="next-steps-section" id="suggested-next-steps-section">
          <div className="next-steps-header">
            <svg
              width="18"
              height="18"
              viewBox="0 0 24 24"
              fill="none"
              stroke="var(--accent-cyan)"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
              aria-hidden="true"
            >
              <polyline points="9 18 15 12 9 6" />
            </svg>
            <span>Suggested Actionable Next Steps</span>
          </div>

          <div className="steps-list" role="list">
            {result.suggestedNextSteps.map((stepItem, idx) => (
              <div key={idx} className="step-card" role="listitem">
                <div className="step-number">{idx + 1}</div>
                <div className="step-content">
                  <div className="step-text">{stepItem.step}</div>
                  <span className="step-badge">
                    Audience: {stepItem.audience}
                  </span>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Raw JSON toggle */}
        {showRawJson && (
          <div className="json-view-container" id="raw-json-viewer">
            <pre>{JSON.stringify(result, null, 2)}</pre>
          </div>
        )}

        {/* Metadata Footer */}
        <div className="result-footer-metadata">
          <span>Engine: {result.metadata.analysisMode} ({result.metadata.modelUsed})</span>
          <span>Assessed: {new Date(result.metadata.timestamp).toLocaleTimeString()}</span>
        </div>
      </div>
    </section>
  );
};
